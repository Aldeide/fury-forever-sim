export function getTalentsByTree(tree: 'arms' | 'fury' | 'protection'): TalentTreeNode[] {
  return TALENT_NODES.filter((n) => n.tree === tree);
}

export function calculateSpentPoints(config: TalentConfig): {
  arms: number;
  fury: number;
  protection: number;
  total: number;
} {
  let arms = 0;
  let fury = 0;
  let protection = 0;

  for (const node of TALENT_NODES) {
    const rank = Math.min(node.maxRank, Math.max(0, Number(config[node.id] || 0)));
    if (node.tree === 'arms') arms += rank;
    else if (node.tree === 'fury') fury += rank;
    else if (node.tree === 'protection') protection += rank;
  }

  return { arms, fury, protection, total: arms + fury + protection };
}

export const calculateTalentPoints = calculateSpentPoints;

