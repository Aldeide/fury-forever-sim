export const ITEM_LOOKUP: Map<string, ItemStats> = new Map(
  ITEMS_DATABASE.map((item) => [item.id, item])
);

export function getItemById(id: string): ItemStats | undefined {
  return ITEM_LOOKUP.get(id);
}

/**
 * Returns available items for a specific character equipment slot.
 * Rings (ring1, ring2) share the 'ring' slot items.
 * Trinkets (trinket1, trinket2) share the 'trinket' slot items.
 * Main-hand allows 'onehand' or 'mainhand'.
 * Off-hand allows 'onehand' or 'offhand'.
 * Two-hand allows 'twohand'.
 */
export function getItemsForSlot(
  slot: string,
  allItems: ItemStats[] = ITEMS_DATABASE
): ItemStats[] {
  if (slot === 'ring1' || slot === 'ring2' || slot === 'ring') {
    return allItems.filter((i) => i.slot === 'ring');
  }
  if (slot === 'trinket1' || slot === 'trinket2' || slot === 'trinket') {
    return allItems.filter((i) => i.slot === 'trinket');
  }
  if (slot === 'mainhand') {
    return allItems.filter(
      (i) => i.slot === 'onehand' || i.slot === 'mainhand'
    );
  }
  if (slot === 'offhand') {
    return allItems.filter(
      (i) => i.slot === 'onehand' || i.slot === 'offhand'
    );
  }
  if (slot === 'twohand') {
    return allItems.filter((i) => i.slot === 'twohand');
  }
  return allItems.filter((i) => i.slot === slot);
}
